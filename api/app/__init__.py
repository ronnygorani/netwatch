# This file is intentionally empty.
#
# Its presence is what matters: it tells Python that the "app"
# folder is a PACKAGE — a collection of modules you can import.
#
# Without this file, Python treats the folder as a plain directory.
# With it, you can write:
#   from app.config import settings
#   from app.database import get_db
#
# Every folder that contains Python code you want to import from
# needs one of these files.
